def main():
    from build_places import build_dataset
    regions, cities, categories, tags = build_dataset()
    places = generate_all_places()

    # Verify all city_slugs, category_slugs, tag_slugs
    valid_cities = {c["slug"] for c in cities}
    valid_categories = {c["slug"] for c in categories}
    valid_tags = {t["slug"] for t in tags}

    for p in places:
        assert p["city_slug"] in valid_cities, f"Invalid city_slug in place {p['name']}: {p['city_slug']}"
        assert p["category_slug"] in valid_categories, f"Invalid category_slug in place {p['name']}: {p['category_slug']}"
        for t in p["tag_slugs"]:
            assert t in valid_tags, f"Invalid tag_slug in place {p['name']}: {t}"

    dataset = {
        "regions": regions,
        "cities": cities,
        "categories": categories,
        "tags": tags,
        "places": places
    }

    out_path = Path(__file__).resolve().parent / "raw" / "pakistan_places.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(dataset, f, indent=2, ensure_ascii=False)

    print(f"Successfully generated {len(places)} places across {len(cities)} cities and {len(regions)} regions into {out_path}")

if __name__ == "__main__":
    main()
